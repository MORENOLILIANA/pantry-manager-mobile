/** Translate a single ingredient name using the static map */
export function translateIngredient(en: string): string {
  const lower = en.toLowerCase().trim();
  return EN_TO_ES[lower] ?? en;
}

// ─── MyMemory free API (no key required, ~1000 words/day free) ───────────────

function decodeHtmlEntities(text: string): string {
  return text
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&nbsp;/g, " ");
}

async function translateChunk(text: string): Promise<string> {
  if (!text.trim()) return text;
  try {
    const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(text)}&langpair=en|es`;
    const res = await fetch(url);
    const json = await res.json();
    const translated: string = json?.responseData?.translatedText ?? "";
    // Detect quota-exceeded message or bad response
    if (
      !translated ||
      translated.toUpperCase().includes("MYMEMORY.COM") ||
      json?.responseStatus !== 200
    ) {
      return text;
    }
    return decodeHtmlEntities(translated);
  } catch {
    return text;
  }
}

/**
 * Translate English text → Spanish using MyMemory API.
 * Long texts are split into sentence-level chunks to respect the 5000-char limit.
 */
export async function translateToSpanish(text: string): Promise<string> {
  if (!text?.trim()) return text;

  const LIMIT = 4500;
  if (text.length <= LIMIT) {
    return translateChunk(text);
  }

  // Split by sentence-ending punctuation
  const raw = text.match(/[^.!?]*[.!?]+[\s]*/g) || [text];
  const chunks: string[] = [];
  let current = "";

  for (const sentence of raw) {
    if (current.length + sentence.length > LIMIT) {
      if (current) chunks.push(current.trim());
      current = sentence;
    } else {
      current += sentence;
    }
  }
  if (current.trim()) chunks.push(current.trim());

  // Translate chunks sequentially to avoid hammering the free API
  const results: string[] = [];
  for (const chunk of chunks) {
    results.push(await translateChunk(chunk));
  }
  return results.join(" ");
}
